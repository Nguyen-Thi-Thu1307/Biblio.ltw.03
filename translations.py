def get_language():
    if has_request_context():
        language = session.get("language", "vi")
        if language in TRANSLATIONS:
            return language
    return "vi"


def tr(key, **values):
    message = TRANSLATIONS[get_language()].get(key, key)
    return message.format(**values) if values else message
